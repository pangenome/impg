def contig_class(contig, component):
    """The physical location class of a panel path's contig."""
    if contig == component:
        return "component"
    if contig.startswith("block"):
        return "scaffold"
    return "other_chromosome"


class CensusRecord:
    """One routed record's census row, with its occurrence structure
    projected onto graph nodes (the covered shared-segment node ids,
    per matched interval, in path order)."""

    __slots__ = (
        "index", "share", "multiplicity", "t_r", "total",
        "pair_bins", "occ_path", "occ_start", "occ_parts", "occ_contig",
        "occ_contig_class", "occ_truth", "occ_nodes", "occ_edges",
        "key_nodes", "key_edges",
    )

    def __init__(self, row, names, truth_path_set, component):
        self.index = row["record"]
        self.share = row["share"]
        self.multiplicity = row["multiplicity"]
        self.t_r = row["t_r"]
        self.total = row["total_occurrences"]
        self.pair_bins = row["pair_bins"]
        self.occ_path = []
        self.occ_start = []
        self.occ_parts = []
        self.occ_contig = []
        self.occ_contig_class = []
        self.occ_truth = []
        self.occ_nodes = []
        self.occ_edges = []
        self.key_nodes = {}
        self.key_edges = {}
        for occ in row["occurrences"]:
            path = occ["path"]
            nodes = set()
            edges = set()
            for interval in occ["intervals"]:
                previous = None
                for node in interval:
                    nodes.add(node)
                    if previous is not None:
                        edges.add(pack_edge(previous, node))
                    previous = node
            self.occ_path.append(path)
            self.occ_start.append(occ["start"])
            self.occ_parts.append(tuple(occ["partitions"]))
            self.occ_contig.append(names[path][1])
            self.occ_contig_class.append(contig_class(names[path][1], component))
            self.occ_truth.append(path in truth_path_set)
            self.occ_nodes.append(nodes)
            self.occ_edges.append(edges)
            position = len(self.occ_nodes) - 1
            for node in nodes:
                self.key_nodes.setdefault(node, []).append(position)
            for edge in edges:
                self.key_edges.setdefault(edge, []).append(position)

    def homing_at(self, locus):
        """Truth-path occurrences touching the locus's window."""
        return [
            position
            for position in range(len(self.occ_path))
            if self.occ_truth[position] and locus in self.occ_parts[position]
        ]

    def homing_any(self):
        return any(self.occ_truth)


def pack_edge(left, right):
    return (left << 32) | right


def pair_bin_python(record, left, right, component_contig):
    """Independent Python re-derivation of multi_census_pair_bin (the
    committed physical classifier)."""
    nodes_a = record.occ_nodes[left]
    nodes_b = record.occ_nodes[right]
    parts_a = record.occ_parts[left]
    parts_b = record.occ_parts[right]
    coalesced = not nodes_a.isdisjoint(nodes_b)
    if not set(parts_a).isdisjoint(parts_b):
        physical = 0
    elif any(abs(p - q) == 1 for p in parts_a for q in parts_b):
        physical = 1
    elif (
        record.occ_contig[left] == component_contig
        and record.occ_contig[right] == component_contig
    ):
        physical = 2
    else:
        physical = 3
    return physical if coalesced else physical + 4


class AlignmentCache:
    """The syng's own alignment provenance, as dumped by the
    `syng_homology_dump` receipt runs: per (query path, window) the
    homologous intervals the syng reported for each requested target.

    aligned(A, B, w) := the syng, queried from path A's window-w extent,
    reports at least one homologous interval on path B (ANY strand — the
    node projection is orientation-free, so an inverted homolog is still
    aligned-together) overlapping B's window-w extent. B's window-w
    extent is the territory axis range when B sits on the component's
    own contig, else the hull of B's census-matched material in window w
    (the matched spans are inside [start, start + READ_LENGTH))."""

    def __init__(self, path, axis, hulls, names, component):
        self.axis = axis
        self.hulls = hulls
        self.names = names
        self.component = component
        self.intervals = collections.defaultdict(list)
        self.markers = {}
        self.emitted = collections.Counter()  # (query, window) -> interval lines
        with open(path) as handle:
            for line in handle:
                row = json.loads(line)
                if row.get("request_done"):
                    self.markers[(row["query_path"], row["window"])] = (
                        row["qs"], row["qe"], row["hits"],
                    )
                else:
                    self.intervals[(row["query_path"], row["window"], row["target_path"])].append(
                        (row["start"], row["end"])
                    )
                    self.emitted[(row["query_path"], row["window"])] += 1
        self.aligned_memo = {}

    def extent(self, path, window):
        if self.names[path][1] == self.component:
            return self.axis[window][0], self.axis[window][1]
        lo, hi = self.hulls[(path, window)]
        return lo, hi

    def aligned(self, query_path, target_path, window):
        key = (query_path, target_path, window)
        if key in self.aligned_memo:
            return self.aligned_memo[key]
        lo, hi = self.extent(target_path, window)
        result = any(
            start < hi and lo < end
            for (start, end) in self.intervals.get((query_path, window, target_path), ())
        )
        self.aligned_memo[key] = result
        return result

    def aligned_pair(self, left_path, right_path, window):
        """Symmetric: either direction's syng homology ties the window."""
        return self.aligned(left_path, right_path, window) or self.aligned(
            right_path, left_path, window
        )


