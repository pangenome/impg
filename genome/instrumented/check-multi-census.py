def _post_bin(record, covering, locus, component, cache, truth, homing):
    """The post-projection bin of one off-truth key's covering structure:
      (f)  2+ covering occurrences (the same node at multiple locations);
      (g)/(h) for homing records: the covering occurrence shares a window
              with one of the record's truth occurrences — aligned
              together per the syng or not;
           for non-homing records: the covering occurrence sits in the
              locus's own window — aligned with a truth path over that
              window per the syng or not;
      (i)/(j) no shared window: same component chromosome vs other
              contig (adjacent pairs arise only in the pair table; here
              every other-window relation is (i))."""
    if len(covering) >= 2:
        return F
    best = None
    for position in covering:
        if record.occ_truth[position]:
            continue
        parts = set(record.occ_parts[position])
        if homing:
            truth_positions = [
                other
                for other in range(len(record.occ_path))
                if record.occ_truth[other]
            ]
            shared_windows = set()
            for other in truth_positions:
                shared_windows |= parts & set(record.occ_parts[other])
            if shared_windows:
                candidate = (
                    G
                    if any(
                        cache.aligned_pair(
                            record.occ_path[position],
                            record.occ_path[other],
                            window,
                        )
                        for other in truth_positions
                        for window in parts & set(record.occ_parts[other])
                    )
                    else H
                )
            elif record.occ_contig[position] == component:
                candidate = I_FAR
            else:
                candidate = J
        else:
            if locus in parts:
                candidate = (
                    G
                    if any(
                        cache.aligned(record.occ_path[position], path, locus)
                        for path in truth
                    )
                    else H
                )
            elif record.occ_contig[position] == component:
                candidate = I_FAR
            else:
                candidate = J
        if best is None or POST_BINS.index(candidate) < POST_BINS.index(best):
            best = candidate
    return best if best is not None else H


HOMING_TARGET = {
    F: "f_homing", G: "g_homing", H: "h_homing", HSP: "h_homing",
    I_ADJ: "i_homing", I_FAR: "i_homing", J: "j_homing",
}
NONHOMING_TARGET = {
    F: "f_nonhoming", G: "g_nonhoming", H: "h_nonhoming", HSP: "h_nonhoming",
    I_ADJ: "i_nonhoming", I_FAR: "i_nonhoming", J: "j_nonhoming",
}


def _account_key(
    table, record, covering, share, key, truth_set, winner_set,
    locus, component, cache, truth, homing, truth_walk,
):
    """Account one (record, key) share unit into the per-locus table (see
    the module docstring's bin semantics). Every key lands in exactly one
    bin; the homing and non-homing decompositions each conserve their
    record classes' mass exactly."""
    in_truth = key in truth_set
    in_winner = key in winner_set
    if in_winner:
        table["winner_total"] += share
        if in_truth:
            table["winner_shared"] += share
    if in_truth:
        if homing:
            table["collected_homing"] += share
        else:
            table["collected_nonhoming"] += share
        return
    # Off the truth pair's usage.
    truth_covered = any(record.occ_truth[position] for position in covering)
    on_truth_sequence = key in truth_walk
    if in_winner:
        if len(covering) == 1 and truth_covered:
            table["winner_extra_frame"] += share
        else:
            post = _post_bin(record, covering, locus, component, cache, truth, homing)
            table["winner_extra"][post] += share
            if on_truth_sequence:
                table["on_truth_sequence"][post] += share
            else:
                table["off_truth_sequence"][post] += share
    if len(covering) >= 2:
        if homing:
            table["f_homing"] += share
            if truth_covered:
                table["f_homing_truth_covered"] += share
        else:
            table["f_nonhoming"] += share
        if on_truth_sequence:
            table["on_truth_sequence"][F] += share
        else:
            table["off_truth_sequence"][F] += share
        return
    if len(covering) == 1 and truth_covered:
        # A truth route's own material, unspelled by the truth candidate.
        if homing:
            table["frame_homing"] += share
        else:
            table["frame_nonhoming"] += share
        return
    post = _post_bin(record, covering, locus, component, cache, truth, homing)
    if homing:
        table[HOMING_TARGET[post]] += share
    else:
        table[NONHOMING_TARGET[post]] += share
    if on_truth_sequence:
        table["on_truth_sequence"][post] += share
    else:
        table["off_truth_sequence"][post] += share


