def _merged_spans(spans):
    spans = sorted(spans)
    out = []
    for lo, hi in spans:
        if out and lo <= out[-1][1]:
            out[-1][1] = max(out[-1][1], hi)
        else:
            out.append([lo, hi])
    return out


def _near_twin_report(component, left, right):
    """The condensation answer for one named near-twin route pair, from
    the walk and homology receipts: shared vs parallel nodes, and where
    the distinguishing material sits."""
    base = f"{SCRATCH}/{component}"
    walks = {}
    for path in (left, right):
        steps = []
        with open(f"{base}/near-twin-walk-{path}.tsv") as handle:
            for line in handle:
                bp, node = line.split()
                steps.append((int(bp), int(node)))
        walks[path] = steps
    left_nodes = {abs(node) for _, node in walks[left]}
    right_nodes = {abs(node) for _, node in walks[right]}
    shared = left_nodes & right_nodes
    print(
        f"      walks: {len(walks[left]):,d} steps vs {len(walks[right]):,d} steps; "
        f"shared nodes {len(shared):,d} "
        f"({100.0 * len(shared) / len(left_nodes):.1f}% of left's {len(left_nodes):,d} nodes, "
        f"{100.0 * len(shared) / len(right_nodes):.1f}% of right's {len(right_nodes):,d})"
    )
    # The syng's own alignment provenance between the twins, full anchors:
    # the anchors ARE the shared syncmers the syng itself chains.
    anchor_count = 0
    anchored_nodes = set()
    covered_left = []
    covered_right = []
    with open(f"{base}/near-twin-homology-{left}-{right}.jsonl") as handle:
        for line in handle:
            row = json.loads(line)
            if row.get("request_done") or row["target_path"] != right:
                continue
            for query_pos, target_pos, node in row["anchors"]:
                anchor_count += 1
                anchored_nodes.add(node)
                covered_left.append((query_pos, query_pos + K))
                covered_right.append((target_pos, target_pos + K))
    left_covered = _merged_spans(covered_left)
    right_covered = _merged_spans(covered_right)
    left_bp = sum(hi - lo for lo, hi in left_covered)
    right_bp = sum(hi - lo for lo, hi in right_covered)
    left_len = walks[left][-1][0] + K if walks[left] else 1
    right_len = walks[right][-1][0] + K if walks[right] else 1
    print(
        f"      syng homology {left}->{right}: {anchor_count:,d} shared-syncmer anchors "
        f"({len(anchored_nodes):,d} distinct nodes), aligned coverage "
        f"{left_bp:,d} bp of left ({100.0 * left_bp / left_len:.1f}%), "
        f"{right_bp:,d} bp of right ({100.0 * right_bp / right_len:.1f}%)"
    )
    incidental = shared - anchored_nodes
    print(
        f"      shared-node structure: {len(anchored_nodes):,d} chained by the syng's "
        f"anchors, {len(incidental):,d} shared but outside the anchor chain"
    )
    # The distinguishing material: maximal runs of consecutive steps whose
    # nodes the other twin does not carry.
    for path, other_nodes, label in ((left, right_nodes, "left"), (right, left_nodes, "right")):
        runs = []
        run = None
        for bp, node in walks[path]:
            if abs(node) not in other_nodes:
                if run is None:
                    run = [bp, bp + K]
                else:
                    run[1] = bp + K
            else:
                if run is not None:
                    runs.append(tuple(run))
                    run = None
        if run is not None:
            runs.append(tuple(run))
        runs_by_size = sorted(runs, key=lambda span: span[1] - span[0], reverse=True)
        print(
            f"      {label}-only (parallel) material: {len(runs_by_size)} runs, "
            f"{sum(span[1] - span[0] for span in runs_by_size):,d} bp; "
            f"largest {['%d-%d' % span for span in runs_by_size[:5]]}"
        )


if __name__ == "__main__":
    sys.exit(main())
